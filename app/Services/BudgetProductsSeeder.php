    public static function seedIfNeeded(): void
    {
        // Cek jika produk budget laptop sudah ada setidaknya 25 item
        $existingBudgetLaptops = Product::where('price', '<=', 5000000)
            ->whereHas('category', function ($q) {
                $q->where('slug', 'laptop-gaming');
            })
            ->count();

        if ($existingBudgetLaptops >= 25) {
            return;
        }

        $shop = Shop::first();
        if (!$shop) {
            return;
        }

        $categories = Category::all()->keyBy('slug');
        if ($categories->isEmpty()) {
            return;
        }

        $items = self::getBudgetProductsData();

        foreach ($items as $data) {
            $catSlug = $data['cat_slug'];
            $category = $categories[$catSlug] ?? $categories->first();

            $product = Product::firstOrCreate(
                ['slug' => $data['slug']],
                [
                    'shop_id' => $shop->id,
                    'category_id' => $category->id,
                    'name' => $data['name'],
                    'sku' => $data['sku'],
                    'price' => $data['price'],
                    'discount_price' => $data['discount_price'],
                    'stock' => $data['stock'],
                    'weight' => $data['weight'] ?? 1500,
                    'condition' => 'new',
                    'rating_avg' => $data['rating_avg'],
                    'reviews_count' => $data['reviews_count'],
                    'sales_count' => $data['sales_count'],
                    'views_count' => $data['sales_count'] * 6,
                    'description' => $data['description'],
                    'is_active' => true,
                ]
            );

            // Seed Image
            if (!empty($data['images'])) {
                foreach ($data['images'] as $idx => $img) {
                    ProductImage::firstOrCreate(
                        ['product_id' => $product->id, 'sort_order' => $idx],
                        [
                            'image_path' => $img,
                            'is_primary' => $idx === 0,
                        ]
                    );
                }
            }

            // Seed Variants if any
            if (!empty($data['variants'])) {
                foreach ($data['variants'] as $v) {
                    ProductVariant::firstOrCreate(
                        ['product_id' => $product->id, 'value' => $v['value']],
                        [
                            'name' => $v['name'],
                            'price_adjustment' => $v['price_adjustment'],
                            'stock' => $v['stock'],
                            'sku' => $product->sku . '-' . Str::slug($v['value']),
                        ]
                    );
                }
            }
        }
    }

